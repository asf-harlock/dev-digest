import { Document, isMap, isPair, isScalar, isSeq, parseDocument, type Node } from 'yaml';
import {
  ARTIFACT_NAME,
  NODE_VERSION,
  OPENROUTER_SECRET_NAME,
  PINNED_ACTIONS,
  RESULT_FILENAME,
  RUNNER_ENTRYPOINT,
  RUN_META_FILENAME,
  SIDECAR_SCRIPT,
  TRIGGER_ORDER,
  WORKFLOW_ERROR_NOT_YAML,
  WORKFLOW_ERROR_TOO_LARGE,
  WORKFLOW_HEADER_ACTION_REF,
  WORKFLOW_JOB_ID,
  WORKFLOW_JOB_TIMEOUT_MINUTES,
  WORKFLOW_MAX_BYTES,
  WORKFLOW_NAME,
  WORKFLOW_RUNS_ON,
  WORKFLOW_VERSION,
} from './constants.js';
import { ValidationError } from '../../platform/errors.js';

/**
 * The generated GitHub Actions workflow (AC-21..AC-27, NFR-5..NFR-7).
 *
 * Built as an object and serialised by `yaml` — never by concatenating text.
 * Nothing from the PR (`github.event.*` title/body/branch) or from an agent
 * reaches a `run:` line (UI-7): values travel only through `env:`.
 */

export type WorkflowTrigger = (typeof TRIGGER_ORDER)[number];
export type WorkflowPostAs = 'github_review' | 'pr_comment' | 'none';

export interface WorkflowOptions {
  triggers: readonly WorkflowTrigger[];
  postAs: WorkflowPostAs;
}

/** Selected triggers, de-duplicated, in the canonical order (AC-21). */
export function orderTriggers(triggers: readonly WorkflowTrigger[]): WorkflowTrigger[] {
  const chosen = new Set(triggers);
  return TRIGGER_ORDER.filter((t) => chosen.has(t));
}

function headerComment(): string {
  return [
    ` Generated by DevDigest — workflow version ${WORKFLOW_VERSION}.`,
    ` Equivalent hosted action: ${WORKFLOW_HEADER_ACTION_REF} (not used by this file).`,
    ' Edit the file here or re-export it from DevDigest to regenerate it.',
  ].join('\n');
}

function pinned(action: { uses: string; version: string }): { uses: string } {
  return { uses: action.uses };
}

/** The workflow as a plain object — exported for tests. */
export function buildWorkflowObject(options: WorkflowOptions): Record<string, unknown> {
  const triggers = orderTriggers(options.triggers);
  if (triggers.length === 0) throw new ValidationError('Select at least one trigger');

  const permissions: Record<string, string> = { contents: 'read' };
  if (options.postAs !== 'none') permissions['pull-requests'] = 'write';

  return {
    name: WORKFLOW_NAME,
    on: { pull_request: { types: triggers } },
    jobs: {
      [WORKFLOW_JOB_ID]: {
        'runs-on': WORKFLOW_RUNS_ON,
        'timeout-minutes': WORKFLOW_JOB_TIMEOUT_MINUTES,
        // Run only on pull requests whose head is THIS repository: a pull request from another
        // repository gets no secrets and a read-only token. Compare repositories, not the `fork`
        // flag: a repository that is itself a fork has `fork: true` on every one of its own PRs.
        if: 'github.event.pull_request.head.repo.full_name == github.repository',
        permissions,
        steps: [
          {
            name: 'Check out',
            ...pinned(PINNED_ACTIONS.checkout),
            with: { 'persist-credentials': false },
          },
          {
            name: 'Set up Node.js',
            ...pinned(PINNED_ACTIONS.setupNode),
            with: { 'node-version': NODE_VERSION },
          },
          {
            name: 'Run DevDigest review',
            run: `node ${RUNNER_ENTRYPOINT}`,
            env: {
              [OPENROUTER_SECRET_NAME]: `\${{ secrets.${OPENROUTER_SECRET_NAME} }}`,
              GITHUB_TOKEN: '${{ secrets.GITHUB_TOKEN }}',
              GITHUB_REPOSITORY: '${{ github.repository }}',
              PR_NUMBER: '${{ github.event.pull_request.number }}',
              DEVDIGEST_POST_AS: options.postAs,
            },
          },
          {
            name: 'Record run metadata',
            if: 'always()',
            run: SIDECAR_SCRIPT,
            env: {
              DEVDIGEST_COMMIT_SHA: '${{ github.event.pull_request.head.sha }}',
              DEVDIGEST_REPOSITORY: '${{ github.repository }}',
              DEVDIGEST_PR_NUMBER: '${{ github.event.pull_request.number }}',
            },
          },
          {
            name: 'Upload result',
            if: 'always()',
            ...pinned(PINNED_ACTIONS.uploadArtifact),
            with: {
              name: ARTIFACT_NAME,
              path: `${RESULT_FILENAME}\n${RUN_META_FILENAME}`,
              'if-no-files-found': 'warn',
            },
          },
        ],
      },
    },
  };
}

/** Attach the `# vX.Y.Z` comment next to every pinned `uses:` SHA. */
function annotatePins(doc: Document): void {
  const versions = new Map<string, string>(
    Object.values(PINNED_ACTIONS).map((a) => [a.uses, a.version]),
  );
  const jobs = doc.getIn(['jobs', WORKFLOW_JOB_ID, 'steps']);
  if (!isSeq(jobs)) return;
  for (const step of jobs.items) {
    if (!isMap(step)) continue;
    for (const pair of step.items) {
      if (!isPair(pair) || !isScalar(pair.key) || pair.key.value !== 'uses') continue;
      const value = pair.value;
      if (isScalar(value) && typeof value.value === 'string') {
        const version = versions.get(value.value);
        if (version) value.comment = ` ${version}`;
      }
    }
  }
}

/** Serialise the workflow. Deterministic: same options, same bytes (NFR-5). */
export function buildWorkflowYaml(options: WorkflowOptions): string {
  const doc = new Document(buildWorkflowObject(options));
  doc.commentBefore = headerComment();
  annotatePins(doc);
  return doc.toString({ lineWidth: 0 });
}

export type WorkflowValidation = { ok: true } | { ok: false; message: string };

/**
 * Check a hand-edited workflow from the client (UI-3, EC-11): valid YAML, at
 * most 64 KiB. Returns the parser message so the dialog can show it.
 */
export function validateWorkflowYaml(text: string): WorkflowValidation {
  if (Buffer.byteLength(text, 'utf8') > WORKFLOW_MAX_BYTES) {
    return { ok: false, message: WORKFLOW_ERROR_TOO_LARGE };
  }
  const doc = parseDocument(text);
  const first = doc.errors[0];
  if (first) return { ok: false, message: first.message };
  const contents: Node | null = doc.contents as Node | null;
  if (!isMap(contents)) return { ok: false, message: `${WORKFLOW_ERROR_NOT_YAML}: expected a mapping at the top level` };
  return { ok: true };
}

/** Like `validateWorkflowYaml`, but throws a 422 `ValidationError` carrying the parser message. */
export function assertValidWorkflowYaml(text: string): void {
  const result = validateWorkflowYaml(text);
  if (!result.ok) throw new ValidationError(result.message);
}
